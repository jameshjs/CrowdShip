import { buildResultsReport, type ResultsReport } from "@crowdship/db";
import { route } from "@/lib/api";
import { requireRoomOrganizer } from "@/lib/auth";
import { roomCode, type RoomCtx } from "@/lib/room-params";

export const dynamic = "force-dynamic";

/** Organizer-only results export: ?format=md (default) or csv, optional ?round=N. */
export const GET = route<RoomCtx>(async (req, ctx) => {
  const { room } = await requireRoomOrganizer(await roomCode(ctx));
  const url = new URL(req.url);
  const n = Number(url.searchParams.get("round"));
  const report = await buildResultsReport(room.id, Number.isInteger(n) && n > 0 ? n : undefined);
  const csv = url.searchParams.get("format") === "csv";
  const name = `crowdship-${room.code.toLowerCase()}-round-${report.round?.number ?? 0}.${csv ? "csv" : "md"}`;
  return new Response(csv ? toCsv(report) : toMarkdown(report), {
    headers: {
      "Content-Type": csv ? "text/csv; charset=utf-8" : "text/markdown; charset=utf-8",
      "Content-Disposition": `attachment; filename="${name}"`,
      "Cache-Control": "no-store",
    },
  });
});

// User text is quoted as data: escape Markdown control characters so feedback can't inject links or formatting.
const md = (s: string) => s.replace(/[\\`*_{}[\]()#+\-.!|<>]/g, "\\$&").replace(/\s+/g, " ").trim();

function toMarkdown(r: ResultsReport): string {
  const lines = [
    `# ${md(r.projectName)}: what users want`,
    "",
    r.website ? `Website reviewed: ${r.website}` : "",
    `CrowdShip session ${r.roomCode}${r.round ? `, round ${r.round.number}` : ""}. ${r.totals.participants} participants, ${r.totals.feedback} pieces of feedback, ${r.totals.votes} votes.`,
    "",
  ];
  if (!r.ranked.length) lines.push("_No vote has been held yet._");
  for (const p of r.ranked) {
    lines.push(`## ${p.rank}. ${md(p.title)}${p.winner ? " (top pick)" : ""}`, "", `**${p.votes} vote${p.votes === 1 ? "" : "s"}**${p.likes + p.dislikes ? ` · swipe approval ${Math.round((p.likes / (p.likes + p.dislikes)) * 100)}% (${p.likes} ▲ / ${p.dislikes} ▼)` : ""} · ${p.supporters} ${p.supporters === 1 ? "person" : "people"} suggested it`, "");
    if (p.description) lines.push(md(p.description), "");
    if (p.requirements.length) lines.push("What it should do:", ...p.requirements.map((x) => `- ${md(x)}`), "");
    if (p.quotes.length) lines.push("In their words:", ...p.quotes.map((q) => `> "${md(q.text)}" (${md(q.nickname)}${q.where ? `, ${md(q.where)}` : ""})`), "");
  }
  lines.push("---", "Generated by CrowdShip. Votes are one per guest session, not verified identities.");
  return lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n") + "\n";
}

// Neutralize spreadsheet formula injection (=, +, -, @ at the start of a cell).
const cell = (v: string | number) => {
  let s = String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return `"${s.replace(/"/g, '""')}"`;
};

function toCsv(r: ResultsReport): string {
  const head = ["rank", "proposal", "votes", "swipe_likes", "swipe_dislikes", "supporters", "top_pick", "description", "requirements", "quotes"];
  const rows = r.ranked.map((p) => [
    p.rank, p.title, p.votes, p.likes, p.dislikes, p.supporters, p.winner ? "yes" : "no", p.description, p.requirements.join(" | "),
    p.quotes.map((q) => `${q.nickname}: ${q.text}`).join(" | "),
  ]);
  return [head, ...rows].map((row) => row.map(cell).join(",")).join("\r\n") + "\r\n";
}
